const (
	DeadletterReasonUnspecified           DeadletterReason = 0
	DeadletterReasonNoActiveSnapshot      DeadletterReason = 1
	DeadletterReasonRouteMiss             DeadletterReason = 2
	DeadletterReasonNoResponsibleHost     DeadletterReason = 3
	DeadletterReasonQueueRejected         DeadletterReason = 4
	DeadletterReasonLocalHandoffFailed    DeadletterReason = 5
	DeadletterReasonDeliveryFailed        DeadletterReason = 6
	DeadletterReasonTransportSendFailed   DeadletterReason = 7
	DeadletterReasonRuntimeStopped        DeadletterReason = 8
	DeadletterReasonInvalidEnvelope       DeadletterReason = 9
	DeadletterReasonEndpointUnavailable   DeadletterReason = 10
	DeadletterReasonRemoteReplyTimeout    DeadletterReason = 11
	DeadletterReasonLocalityMismatch      DeadletterReason = 12
	DeadletterReasonExpiredBeforeDelivery DeadletterReason = 13
	DeadletterReasonOneWayDroppedByPolicy DeadletterReason = 14
)

func (r DeadletterReason) String() string {
	switch r {
	case DeadletterReasonUnspecified:
		return "UNSPECIFIED"
	case DeadletterReasonNoActiveSnapshot:
		return "NO_ACTIVE_SNAPSHOT"
	case DeadletterReasonRouteMiss:
		return "ROUTE_MISS"
	case DeadletterReasonNoResponsibleHost:
		return "NO_RESPONSIBLE_HOST"
	case DeadletterReasonQueueRejected:
		return "QUEUE_REJECTED"
	case DeadletterReasonLocalHandoffFailed:
		return "LOCAL_HANDOFF_FAILED"
	case DeadletterReasonDeliveryFailed:
		return "DELIVERY_FAILED"
	case DeadletterReasonTransportSendFailed:
		return "TRANSPORT_SEND_FAILED"
	case DeadletterReasonRuntimeStopped:
		return "RUNTIME_STOPPED"
	case DeadletterReasonInvalidEnvelope:
		return "INVALID_ENVELOPE"
	case DeadletterReasonEndpointUnavailable:
		return "ENDPOINT_UNAVAILABLE"
	case DeadletterReasonRemoteReplyTimeout:
		return "REMOTE_REPLY_TIMEOUT"
	case DeadletterReasonLocalityMismatch:
		return "LOCALITY_MISMATCH"
	case DeadletterReasonExpiredBeforeDelivery:
		return "EXPIRED_BEFORE_DELIVERY"
	case DeadletterReasonOneWayDroppedByPolicy:
		return "ONE_WAY_DROPPED_BY_POLICY"
	default:
		return fmt.Sprintf("UNKNOWN(%d)", r)
	}
}

// Envelope is the connector-owned message contract exchanged with handlers and
// request APIs. Payload and Headers remain owned by the caller until a submit
// method returns; the connector snapshots them before asynchronous tracking.
// Received envelopes own their Payload and Headers and may be retained by the
// application after the callback returns.
//
// The Id and Ms spellings are retained for source compatibility with earlier
// Go connector releases. Prefer the constructors and Get methods when possible.
type Envelope struct {
	MessageId     string      `json:"message_id,omitempty"`     // Unique message identity supplied or generated by the sender.
	CorrelationId string      `json:"correlation_id,omitempty"` // Request identity shared by its response or terminal deadletter.
	Source        string      `json:"source,omitempty"`         // Logical sender name.
	Target        string      `json:"target,omitempty"`         // Logical route target, not a network address.
	ReplyTo       string      `json:"reply_to,omitempty"`       // Logical reply target; empty for one-way messages.
	Kind          MessageKind `json:"kind,omitempty"`           // Request, response, or event classification.
	OneWay        bool        `json:"one_way,omitempty"`        // True when no response is expected.
	TimeoutMs     int32       `json:"timeout_ms,omitempty"`     // End-to-end delivery budget in milliseconds; zero means unspecified.
	Payload       []byte      `json:"payload,omitempty"`        // Opaque application bytes described by the payload identity fields.

	// Headers carry application metadata. They do not configure connector routing,
	// connection strategy, or transport security.
	Headers map[string]string `json:"headers,omitempty"`

	Status       BusinessStatus `json:"status,omitempty"`        // Application result status, primarily used by responses.
	ErrorCode    string         `json:"error_code,omitempty"`    // Stable application error code when Status is error.
	ErrorMessage string         `json:"error_message,omitempty"` // Human-readable application error detail.
	DeliveryHint DeliveryHint   `json:"delivery_hint,omitempty"` // Routing constraint interpreted by the core runtime.

	MessageType          string        `json:"message_type,omitempty"`           // Stable application schema name.
	PayloadSchemaVersion uint32        `json:"payload_schema_version,omitempty"` // Application schema version; typed APIs require at least one.
	PayloadFormat        PayloadFormat `json:"payload_format,omitempty"`         // Encoding of Payload supplied by the application.
}

