func (f PayloadFormat) String() string {
	switch f {
	case PayloadFormatJSON:
		return "JSON"
	case PayloadFormatProtobuf:
		return "PROTOBUF"
	case PayloadFormatThrift:
		return "THRIFT"
	case PayloadFormatMsgpack:
		return "MSGPACK"
	case PayloadFormatText:
		return "TEXT"
	case PayloadFormatBinary:
		return "BINARY"
	default:
		return "UNSPECIFIED"
	}
}

// DeadletterReason identifies why the runtime could not complete delivery.
// Values are stable across connector languages and may be persisted in
// diagnostics. Callers should retain unknown numeric values when forwarding a
// deadletter so newer runtime reasons remain observable.
